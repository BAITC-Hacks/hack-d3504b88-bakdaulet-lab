export const policySource = "https://ekt.kz/about/information/";
export const policyCheckedAt = "2026-09-23";

export function purchasePolicy(topic: string, city?: string) {
  const lower = topic.toLocaleLowerCase("ru");
  let text: string;
  if (/оплат|карт|наличн|счет|счёт/.test(lower)) {
    text = "Для физических лиц сайт указывает онлайн-оплату картой, наличные при получении и оплату в торговом зале при самовывозе. Для юридических лиц описаны оплата по счёту переводом и оплата в торговом зале при самовывозе.";
  } else if (/достав|самовывоз|город/.test(lower)) {
    text = city?.toLocaleLowerCase("ru") === "алматы"
      ? "Для Алматы опубликованы отдельные условия доставки, зависящие от суммы и адреса. Срок согласованного с менеджером товара указан до 48 часов. Уточните стоимость для вашего адреса на сайте или у менеджера."
      : "Стоимость и сроки доставки в другие города Казахстана согласуются с менеджером по адресу, весу и объёму заказа. Самовывоз указан для городов присутствия компании; точные условия проверьте перед оформлением.";
  } else if (/минимал|парт|кратност/.test(lower)) {
    text = "Подтверждённого общего правила минимальной партии в доступном источнике нет. Для конкретной позиции уточните его у менеджера. Поля кратности каталога не считаем таким правилом без подтверждения.";
  } else {
    text = "На официальной странице есть сведения об оплате и доставке. Уточните, какой именно вопрос вас интересует. Правило минимальной партии для товара в доступных данных не подтверждено.";
  }
  return { text, source: policySource, checkedAt: policyCheckedAt };
}
